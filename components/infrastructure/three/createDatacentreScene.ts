/**
 * The hero's WebGL data-centre aisle.
 *
 * Geometry and baked lighting come from public/models/datacentre.glb, which is
 * generated by tools/blender/build_datacentre.py. This module instances the
 * cabinets, adds everything that moves (LED activity, signal routes, the
 * investigated cabinet, dust) and owns the render loop.
 *
 * It is loaded with a dynamic import so Three.js never weighs on first paint.
 */

export type DatacentreScene = {
  /** Scene progress in 0..1 (camera walk + story). */
  setProgress(value: number): void;
  /** Pointer position within the hero, each axis in -1..1. */
  setPointer(x: number, y: number): void;
  /** Animate continuously (true) or only redraw when something changes (false). */
  setAnimated(animated: boolean): void;
  /** Stop drawing entirely while the hero is off screen or the tab is hidden. */
  setVisible(visible: boolean): void;
  resize(): void;
  dispose(): void;
};

type Options = {
  canvas: HTMLCanvasElement;
  modelUrl: string;
  animated: boolean;
  progress: number;
  onContextLost: () => void;
};

const FOG_COLOR = 0x04111a;
const FOG_DENSITY = 0.062;
const BOOT_SECONDS = 2.6;
const fog = fogUniforms(FOG_COLOR, FOG_DENSITY);
const PLAYBACK_INTENSITY = 2.5;

function signalMaterial(shared: Uniforms, offset: number) {
  return new ShaderMaterial({
    transparent: true,
    depthWrite: false,
    blending: AdditiveBlending,
    side: DoubleSide,
    uniforms: { ...shared, ...fog, uOffset: { value: offset } },
    vertexShader: /* glsl */ `
      varying vec2 vUv;
      varying float vFogDepth;
      void main() {
        vUv = uv;
        vec4 mvPosition = modelViewMatrix * vec4(position, 1.0);
        gl_Position = projectionMatrix * mvPosition;
        ${FOG_VERTEX}
      }`,
    fragmentShader: /* glsl */ `
      uniform float uTime, uTelemetry, uOffset;
      uniform vec3 uFogColor;
      uniform float uFogDensity;
      varying vec2 vUv;
      varying float vFogDepth;
      void main() {
        float drawn = 1.0 - smoothstep(uTelemetry - 0.015, uTelemetry + 0.002, vUv.x);
        float head = smoothstep(uTelemetry - 0.06, uTelemetry, vUv.x) * drawn;
        float travel = fract(vUv.x * 2.2 - uTime * 0.16 + uOffset);
        float pulse = smoothstep(0.9, 1.0, travel) + 0.35 * smoothstep(0.55, 1.0, travel);
        vec3 teal = vec3(0.32, 0.95, 0.86);
        vec3 color = teal * (0.22 + 1.5 * pulse + 1.8 * head);
        gl_FragColor = vec4(color * drawn, 1.0);
        ${FOG_FRAGMENT}
      }`,
  });
}

function dustMaterial(shared: Uniforms, pixelRatio: { value: number }) {
  return new ShaderMaterial({
    transparent: true,
    depthWrite: false,
    blending: AdditiveBlending,
    uniforms: { ...shared, uPixelRatio: pixelRatio },
    vertexShader: /* glsl */ `
      attribute float aSeed;
      uniform float uTime, uPixelRatio;
      varying float vAlpha;
      void main() {
        vec3 p = position;
        p.x += sin(uTime * 0.11 + aSeed * 40.0) * 0.18;
        p.y = 0.15 + mod(p.y + uTime * (0.012 + 0.02 * aSeed), 2.7);
        p.z += cos(uTime * 0.07 + aSeed * 23.0) * 0.25;
        vec4 mvPosition = modelViewMatrix * vec4(p, 1.0);
        gl_Position = projectionMatrix * mvPosition;
        gl_PointSize = uPixelRatio * (1.0 + 1.6 * aSeed) * 1.5 / max(0.8, -mvPosition.z);
        vAlpha = (0.12 + 0.3 * aSeed) * smoothstep(0.3, 1.4, -mvPosition.z) * exp(-0.11 * -mvPosition.z);
      }`,
    fragmentShader: /* glsl */ `
      varying float vAlpha;
      void main() {
        float d = length(gl_PointCoord - 0.5);
        gl_FragColor = vec4(vec3(0.62, 0.9, 0.92) * (1.0 - smoothstep(0.1, 0.5, d)) * vAlpha, 1.0);
      }`,
  });
}

export async function createDatacentreScene({
  canvas,
  modelUrl,
  animated: initiallyAnimated,
  progress: initialProgress,
  onContextLost,
}: Options): Promise<DatacentreScene> {
  const renderer = new WebGLRenderer({
    canvas,
    antialias: false,
    alpha: false,
    powerPreference: "high-performance",
  });
  renderer.outputColorSpace = SRGBColorSpace;
  renderer.toneMapping = ACESFilmicToneMapping;
  renderer.toneMappingExposure = 1.05;
  renderer.setClearColor(FOG_COLOR, 1);

  const disposables: { dispose(): void }[] = [];
  const track = <T extends { dispose(): void }>(item: T) => {
    disposables.push(item);
    return item;
  };

  let model;
  try {
    model = await loadDatacentreModel(modelUrl);
  } catch (error) {
    renderer.dispose();
    throw error;
  }

  const scene = new Scene();
  scene.fog = new FogExp2(FOG_COLOR, FOG_DENSITY);
  const pmrem = new PMREMGenerator(renderer);
  const environment = track(pmrem.fromScene(new RoomEnvironment(), 0.04));
  pmrem.dispose();
  scene.environment = environment.texture;
  scene.environmentIntensity = 0.1;
  // The baked vertex colours carry the lighting; this light just "plays it back".
  const playback = new AmbientLight(0xbfe6f2, PLAYBACK_INTENSITY);
  scene.add(playback);

  const shared = {
    uTime: { value: 0 },
    uBoot: { value: 0 },
    uTelemetry: { value: 0 },
    uInvestigation: { value: 0 },
    uRecovery: { value: 0 },
    uFocus: { value: 0 },
  };
  const pixelRatioUniform = { value: 1 };

  // Everything in here is drawn upside-down under the translucent floor, which
  // reads as a reflection without a second render of the scene.
  const mirror = new Group();
  mirror.scale.y = -1;
  scene.add(mirror);

  // ---- room: floor, architecture, light fixtures
  const glowMaterials: { material: MeshBasicMaterial; base: Color }[] = [];
  for (const name of ["Floor", "Room", "RoomGlow"]) {
    const node = model.getObjectByName(name);
    if (!node) throw new Error(`datacentre.glb is missing "${name}"`);
    for (const mesh of childMeshes(node)) {
      const source = mesh.material as MeshStandardMaterial;
      track(mesh.geometry);
      if (name === "RoomGlow") {
        const gains: Record<string, number> = { light_strip: 1.9, footlight: 1.15, door_light: 1.7 };
        const gain = gains[source.name] ?? 2;
        const base = source.emissive.clone().multiplyScalar(gain);
        const material = track(new MeshBasicMaterial({ color: base.clone(), side: DoubleSide }));
        glowMaterials.push({ material, base });
        mesh.material = material;
      } else {
        source.metalness = Math.min(source.metalness, 0.3);
        if (name === "Floor") {
          source.transparent = true;
          source.opacity = 0.84;
          source.roughness = 0.2;
          source.envMapIntensity = 2.4;
        }
        track(source);
      }
    }
    node.removeFromParent();
    scene.add(node);
    if (name === "RoomGlow") mirror.add(node.clone());
  }

  // ---- cabinets: three Blender variants, instanced into the exported slots
  const slots: { slot: Slot; matrix: Matrix4 }[] = [];
  model.traverse((node) => {
    const slot = parseSlotName(node.name);
    if (slot) slots.push({ slot, matrix: node.matrixWorld.clone() });
  });
  if (slots.length === 0) throw new Error("datacentre.glb has no cabinet slots");

  const instanceMatrix = new Matrix4();
  let alertMatrix: Matrix4 | null = null;
  for (const variant of ["A", "B", "C"] as const) {
    const placed = slots.filter(({ slot }) => slot.variant === variant);
    if (placed.length === 0) continue;
    const rack = model.getObjectByName(`Rack${variant}`);
    const leds = model.getObjectByName(`RackLeds${variant}`);
    if (!rack || !leds) throw new Error(`datacentre.glb is missing cabinet ${variant}`);

    for (const mesh of childMeshes(rack)) {
      const material = track(mesh.material as MeshStandardMaterial);
      material.metalness = Math.min(material.metalness, 0.45);
      const instances = new InstancedMesh(track(mesh.geometry), material, placed.length);
      placed.forEach(({ matrix }, i) => {
        instances.setMatrixAt(i, instanceMatrix.multiplyMatrices(matrix, mesh.matrixWorld));
      });
      instances.instanceMatrix.needsUpdate = true;
      instances.computeBoundingSphere();
      scene.add(instances);
    }

    const material = track(ledMaterial(shared, fog));
    for (const mesh of childMeshes(leds)) {
      const geometry = track(mesh.geometry);
      const seeds = new Float32Array(placed.length);
      const alerts = new Float32Array(placed.length);
      placed.forEach(({ slot }, i) => {
        seeds[i] = seeded(slot.index * 2 + (slot.side === "L" ? 0 : 1));
        const isAlert = slot.side === INVESTIGATED_SLOT.side && slot.index === INVESTIGATED_SLOT.index;
        alerts[i] = isAlert ? 1 : 0;
      });
      geometry.setAttribute("aSeed", new InstancedBufferAttribute(seeds, 1));
      geometry.setAttribute("aAlert", new InstancedBufferAttribute(alerts, 1));
      for (const parent of [scene, mirror]) {
        const instances = new InstancedMesh(geometry, material, placed.length);
        instances.instanceMatrix.setUsage(DynamicDrawUsage);
        placed.forEach(({ matrix }, i) => {
          instances.setMatrixAt(i, instanceMatrix.multiplyMatrices(matrix, mesh.matrixWorld));
        });
        instances.instanceMatrix.needsUpdate = true;
        instances.frustumCulled = false;
        parent.add(instances);
      }
    }
  }
  const alertSlot = slots.find(
    ({ slot }) => slot.side === INVESTIGATED_SLOT.side && slot.index === INVESTIGATED_SLOT.index,
  );
  if (alertSlot) alertMatrix = alertSlot.matrix;

  // ---- the investigated cabinet: outline panel + a light that spills on the aisle
  const alertLight = new PointLight(0xff8a2a, 0, 6, 1.8);
  const alertColor = { amber: new Color(0xff8a2a), green: new Color(0x8cff7a) };
  if (alertMatrix) {
    const panel = new Mesh(track(new PlaneGeometry(0.6, AISLE.rackHeight)), track(alertPanelMaterial(shared, 0.6, AISLE.rackHeight)));
    // Cabinet-local space after export: front faces +Z, origin at the front foot.
    panel.position.set(0, AISLE.rackHeight / 2, 0.03);
    const holder = new Group();
    holder.applyMatrix4(alertMatrix);
    holder.add(panel);
    scene.add(holder);
    alertLight.position.set(0, 1.25, 0.55).applyMatrix4(alertMatrix);
    scene.add(alertLight);
  }

  // ---- signal routes: from cabinets, up to the ceiling and down the aisle
  const signals = new Group();
  const nodeGeometry = track(new SphereGeometry(0.011, 10, 6));
  const nodeMaterial = track(new MeshBasicMaterial({ color: new Color(0.35, 1.25, 1.1) }));
  const routeSources = slots.filter(({ slot }) => slot.index >= 4 && slot.index % 2 === 0);
  routeSources.forEach(({ slot, matrix }, i) => {
    const side = slot.side === "L" ? -1 : 1;
    const start = new Vector3(0, 1.1 + 0.55 * seeded(i + 40), 0.035).applyMatrix4(matrix);
    const lane = side * (0.12 + 0.07 * (i % 5));
    const height = 2.42 + 0.05 * (i % 3);
    const curve = new CatmullRomCurve3(
      [
        start,
        new Vector3(start.x - side * 0.05, start.y + 0.35, start.z),
        new Vector3(start.x - side * 0.1, AISLE.rackHeight + 0.02, start.z - 0.05),
        new Vector3(lane + side * 0.35, height - 0.05, start.z - 0.45),
        new Vector3(lane, height, start.z - 1.1),
        new Vector3(lane * 0.8, height, (start.z + AISLE.endWallZ) / 2),
        new Vector3(lane * 0.35, 2.5, AISLE.endWallZ + 0.9),
        new Vector3(lane * 0.2, 2.42, AISLE.endWallZ + 0.24),
      ],
      false,
      "catmullrom",
      0.35,
    );
    const tube = new Mesh(
      track(new TubeGeometry(curve, 96, 0.0032, 5, false)),
      track(signalMaterial(shared, seeded(i + 9))),
    );
    tube.frustumCulled = false;
    signals.add(tube);
    const node = new Mesh(nodeGeometry, nodeMaterial);
    node.position.copy(start);
    signals.add(node);
  });
  scene.add(signals);

  // ---- dust in the light
  const dustCount = 260;
  const dustPositions = new Float32Array(dustCount * 3);
  const dustSeeds = new Float32Array(dustCount);
  for (let i = 0; i < dustCount; i += 1) {
    dustPositions[i * 3] = (seeded(i * 3 + 1) - 0.5) * 2 * (AISLE.halfWidth - 0.1);
    dustPositions[i * 3 + 1] = seeded(i * 3 + 2) * 2.7;
    dustPositions[i * 3 + 2] = 2 - seeded(i * 3 + 3) * 11;
    dustSeeds[i] = seeded(i + 700);
  }
  const dustGeometry = track(new BufferGeometry());
  dustGeometry.setAttribute("position", new Float32BufferAttribute(dustPositions, 3));
  dustGeometry.setAttribute("aSeed", new Float32BufferAttribute(dustSeeds, 1));
  const dust = new Points(dustGeometry, track(dustMaterial(shared, pixelRatioUniform)));
  dust.frustumCulled = false;
  scene.add(dust);

  // ---- camera + post-processing
  const camera = new PerspectiveCamera(50, 1, 0.05, 40);
  const lookTarget = new Vector3();
  const renderTarget = track(new WebGLRenderTarget(1, 1, { type: HalfFloatType, samples: 4 }));
  const composer = new EffectComposer(renderer, renderTarget);
  composer.addPass(new RenderPass(scene, camera));
  const bloom = new UnrealBloomPass(new Vector2(1, 1), 0.5, 0.6, 0.95);
  composer.addPass(bloom);
  composer.addPass(new OutputPass());

  let width = 0;
  let height = 0;
  let quality = 0;
  function resize() {
    const parent = canvas.parentElement;
    const nextWidth = Math.max(1, Math.round(parent?.clientWidth ?? canvas.clientWidth));
    const nextHeight = Math.max(1, Math.round(parent?.clientHeight ?? canvas.clientHeight));
    const pixelRatio = pixelRatioFor(window.devicePixelRatio, quality);
    width = nextWidth;
    height = nextHeight;
    pixelRatioUniform.value = pixelRatio;
    renderer.setPixelRatio(pixelRatio);
    renderer.setSize(width, height, false);
    composer.setPixelRatio(pixelRatio);
    composer.setSize(width, height);
    camera.aspect = width / height;
    // Keep the aisle readable on tall phones, and push the vanishing point to
    // the right on wide screens so it sits beside the headline, not under it.
    camera.fov = camera.aspect < 0.8 ? 68 : camera.aspect < 1.25 ? 58 : 50;
    const shift = camera.aspect > 1.25 ? 0.2 : 0;
    camera.setViewOffset(width, height, -shift * width, -0.02 * height, width, height);
    camera.updateProjectionMatrix();
    requestFrame();
  }

  // ---- state + loop
  let animated = initiallyAnimated;
  let visible = true;
  let disposed = false;
  let ready = false;
  let frame = 0;
  let last = 0;
  let clock = 0;
  let bootStart = -1;
  let targetProgress = initialProgress;
  let progress = initialProgress;
  const pointerTarget = { x: 0, y: 0 };
  const pointer = { x: 0, y: 0 };
  let slowFrames = 0;
  let measuredFrames = 0;

  function draw(now: number) {
    frame = 0;
    if (disposed || !visible) return;
    const delta = last ? Math.min(0.1, (now - last) / 1000) : 0;
    last = now;

    if (animated) {
      clock += delta;
      if (bootStart < 0) bootStart = clock;
      const ease = 1 - Math.exp(-delta * 4.5);
      progress += (targetProgress - progress) * ease;
      pointer.x += (pointerTarget.x - pointer.x) * ease;
      pointer.y += (pointerTarget.y - pointer.y) * ease;
      shared.uBoot.value = Math.min(1, (clock - bootStart) / BOOT_SECONDS);
    } else {
      progress = targetProgress;
      pointer.x = pointer.y = 0;
      shared.uBoot.value = 1;
    }

    const view = datacentreView(progress, pointer);
    const sway = animated ? 1 : 0;
    camera.position.set(
      view.position[0] + sway * Math.sin(clock * 0.23) * 0.03,
      view.position[1] + sway * Math.sin(clock * 0.31) * 0.014,
      view.position[2],
    );
    lookTarget.set(view.target[0], view.target[1], view.target[2]);
    camera.lookAt(lookTarget);

    const boot = shared.uBoot.value;
    shared.uTime.value = clock;
    shared.uTelemetry.value = view.telemetry * Math.min(1, boot * 1.4);
    shared.uInvestigation.value = view.investigation;
    shared.uRecovery.value = view.recovery;
    // Fixtures strike like fluorescent tubes during the power-on sweep.
    const strike = boot >= 1 ? 1 : Math.min(1, boot * 1.6) * (0.55 + 0.45 * Math.sign(Math.sin(clock * 47) + 0.6));
    for (const { material, base } of glowMaterials) material.color.copy(base).multiplyScalar(strike);
    playback.intensity = PLAYBACK_INTENSITY * (0.25 + 0.75 * Math.min(1, boot * 1.6));
    alertLight.color.copy(alertColor.amber).lerp(alertColor.green, Math.min(1, view.recovery * 1.4));
    alertLight.intensity = 5 * view.investigation + 2.2 * view.recovery;

    composer.render(delta);

    if (animated) {
      // Step the resolution down, then bloom off, on devices that cannot keep up.
      measuredFrames += 1;
      if (delta > 0.028) slowFrames += 1;
      if (measuredFrames >= 90) {
        if (slowFrames > 45 && quality < 3) {
          quality += 1;
          if (quality === 3) bloom.enabled = false;
          else resize();
        }
        measuredFrames = 0;
        slowFrames = 0;
      }
      frame = requestAnimationFrame(draw);
    }
  }

  function requestFrame() {
    if (ready && !frame && !disposed && visible) frame = requestAnimationFrame(draw);
  }

  const handleContextLost = (event: Event) => {
    event.preventDefault();
    onContextLost();
  };
  canvas.addEventListener("webglcontextlost", handleContextLost);

  resize();
  // Compile shaders before the first visible frame so the reveal does not hitch.
  await renderer.compileAsync(scene, camera);
  ready = true;
  draw(performance.now());
  last = 0;

  return {
    setProgress(value) {
      targetProgress = value;
      requestFrame();
    },
    setPointer(x, y) {
      pointerTarget.x = x;
      pointerTarget.y = y;
      requestFrame();
    },
    setAnimated(next) {
      animated = next;
      last = 0;
      requestFrame();
    },
    setVisible(next) {
      visible = next;
      last = 0;
      if (visible) requestFrame();
      else if (frame) {
        cancelAnimationFrame(frame);
        frame = 0;
      }
    },
    resize,
    dispose() {
      disposed = true;
      if (frame) cancelAnimationFrame(frame);
      canvas.removeEventListener("webglcontextlost", handleContextLost);
      for (const item of disposables) item.dispose();
      scene.traverse((node) => {
        const mesh = node as Mesh;
        if (!mesh.isMesh) return;
        mesh.geometry?.dispose();
        const materials = Array.isArray(mesh.material) ? mesh.material : [mesh.material];
        for (const material of materials as Material[]) material?.dispose();
      });
      bloom.dispose();
      composer.dispose();
      renderer.dispose();
    },
  };
}
