/**
 * The whole 3D world behind the page: one continuous route from the hero's
 * cold aisle, through a tunnel and a silo of cabinets, out onto the roof.
 * The page's scroll position chooses where on the route the camera is.
 *
 * Geometry and baked lighting come from public/models/world.glb, generated by
 * tools/blender/build_world.py. Loaded with a dynamic import so Three.js never
 * weighs on first paint.
 */

export type WorldStatus = { zone: string; elevation: number; progress: number };

export type WorldScene = {
  /** The hero's own scrubber, 0..1. */
  setProgress(value: number): void;
  /** Where on the route the camera should be (a stop index, fractional). */
  setJourney(u: number): void;
  setPointer(x: number, y: number): void;
  /** Fly and animate (true), or hold still frames and only redraw on change (false). */
  setAnimated(animated: boolean): void;
  setVisible(visible: boolean): void;
  /** The signal lab injected a fault (true) or recovered (false). */
  setAlert(alerting: boolean): void;
  resize(): void;
  dispose(): void;
};

type Options = {
  canvas: HTMLCanvasElement;
  modelUrl: string;
  animated: boolean;
  progress: number;
  journey: number;
  onContextLost: () => void;
  onStatus?: (status: WorldStatus) => void;
};

const BOOT_SECONDS = 2.6;
// fog colour along the route: [stop, colour]
const AISLE_FOG = new Color(0x04111a);
const TUNNEL_FOG = new Color(0x03080d);
const CORE_FOG = new Color(0x070a10);
const NIGHT_FOG = new Color(0x060b14);
const FOG_COLOURS: [number, Color][] = [
  [0, AISLE_FOG],
  [stopIndex("threshold") + 0.2, AISLE_FOG],
  [stopIndex("tunnel-in") + 0.4, TUNNEL_FOG],
  [stopIndex("tunnel-out"), TUNNEL_FOG],
  [stopIndex("core-reveal") + 0.4, CORE_FOG],
  [stopIndex("oculus"), CORE_FOG],
  [stopIndex("above-oculus"), NIGHT_FOG],
  [LAST_STOP, NIGHT_FOG],
];

function fogColourAt(u: number, out: Color) {
  for (let i = 1; i < FOG_COLOURS.length; i += 1) {
    const [u0, c0] = FOG_COLOURS[i - 1];
    const [u1, c1] = FOG_COLOURS[i];
    if (u <= u1) return out.copy(c0).lerp(c1, Math.max(0, (u - u0) / (u1 - u0)));
  }
  return out.copy(FOG_COLOURS[FOG_COLOURS.length - 1][1]);
}

export async function createWorldScene({
  canvas,
  modelUrl,
  animated: initiallyAnimated,
  progress: initialProgress,
  journey: initialJourney,
  onContextLost,
  onStatus,
}: Options): Promise<WorldScene> {
  const renderer = new WebGLRenderer({ canvas, antialias: false, alpha: false, powerPreference: "high-performance" });
  renderer.outputColorSpace = SRGBColorSpace;
  renderer.toneMapping = ACESFilmicToneMapping;
  renderer.toneMappingExposure = 1.05;

  let model;
  try {
    model = await loadDatacentreModel(modelUrl);
  } catch (error) {
    renderer.dispose();
    throw error;
  }

  const disposables: { dispose(): void }[] = [];
  const track = <T extends { dispose(): void }>(item: T) => {
    disposables.push(item);
    return item;
  };

  const scene = new Scene();
  const fogColour = new Color(0x04111a);
  scene.fog = new FogExp2(fogColour, 0.062);
  const pmrem = new PMREMGenerator(renderer);
  const environment = track(pmrem.fromScene(new RoomEnvironment(), 0.04));
  pmrem.dispose();
  scene.environment = environment.texture;
  scene.environmentIntensity = 0.1;
  // The baked vertex colours carry the lighting; this light just "plays it back".
  const playback = new AmbientLight(0xbfe6f2, 2.5);
  scene.add(playback);

  const shared: Uniforms = {
    uTime: { value: 0 },
    uBoot: { value: 0 },
    uAlert: { value: 0 },
    uRestore: { value: 0 },
  };
  const fog = fogUniforms(0x04111a, 0.062);
  const pixelRatioUniform = { value: 1 };
  const camera = new PerspectiveCamera(50, 1, 0.06, 1400);
  const context: WorldContext = { model, scene, shared, fog, track };
  const parts: Part[] = [
    buildAisle(context, pixelRatioUniform),
    buildTunnel(context),
    buildCore(context),
    buildRoof(context, camera),
    buildThread(context),
  ];

  // ---- post-processing
  const renderTarget = track(new WebGLRenderTarget(1, 1, { type: HalfFloatType, samples: 4 }));
  const composer = new EffectComposer(renderer, renderTarget);
  composer.addPass(new RenderPass(scene, camera));
  const bloom = new UnrealBloomPass(new Vector2(1, 1), 0.4, 0.55, 0.96);
  composer.addPass(bloom);
  composer.addPass(new OutputPass());

  let width = 0;
  let height = 0;
  let quality = 0;
  function resize() {
    const nextWidth = Math.max(1, Math.round(canvas.clientWidth));
    const nextHeight = Math.max(1, Math.round(canvas.clientHeight));
    const pixelRatio = pixelRatioFor(window.devicePixelRatio, quality);
    width = nextWidth;
    height = nextHeight;
    pixelRatioUniform.value = pixelRatio;
    renderer.setPixelRatio(pixelRatio);
    renderer.setSize(width, height, false);
    composer.setPixelRatio(pixelRatio);
    composer.setSize(width, height);
    camera.aspect = width / height;
    requestFrame();
  }

  // ---- state + loop
  let animated = initiallyAnimated;
  let visible = true;
  let disposed = false;
  let ready = false;
  let frameId = 0;
  let last = 0;
  let clock = 0;
  let bootStart = -1;
  let targetProgress = initialProgress;
  let progress = initialProgress;
  let targetJourney = initialJourney;
  let journey = initialJourney;
  let alertTarget = 0;
  let alert = 0;
  let restore = 0;
  const pointerTarget = { x: 0, y: 0 };
  const pointer = { x: 0, y: 0 };
  const lookTarget = new Vector3();
  const right = new Vector3();
  const up = new Vector3();
  let slowFrames = 0;
  let measuredFrames = 0;
  let statusAt = 0;
  let statusText = "";

  function draw(now: number) {
    frameId = 0;
    if (disposed || !visible) return;
    // `elapsed` is real time, so the camera still arrives on time at a low frame
    // rate; `delta` is capped so animations do not leap after a long pause.
    const elapsed = last ? Math.min(1.5, (now - last) / 1000) : 0;
    const delta = Math.min(0.1, elapsed);
    last = now;

    if (animated) {
      clock += delta;
      if (bootStart < 0) bootStart = journey > 1.5 ? -BOOT_SECONDS : clock; // arriving mid-page: already powered on
      const ease = 1 - Math.exp(-elapsed * 4.5);
      progress += (targetProgress - progress) * ease;
      pointer.x += (pointerTarget.x - pointer.x) * ease;
      pointer.y += (pointerTarget.y - pointer.y) * ease;
      journey += (targetJourney - journey) * (1 - Math.exp(-elapsed * 3.4));
      if (Math.abs(targetJourney - journey) < 0.0004) journey = targetJourney;
      alert += (alertTarget - alert) * (1 - Math.exp(-elapsed * 3));
      restore = Math.max(0, restore - elapsed * 0.3);
      shared.uBoot.value = Math.min(1, (clock - bootStart) / BOOT_SECONDS);
    } else {
      progress = targetProgress;
      journey = targetJourney;
      pointer.x = pointer.y = 0;
      alert = alertTarget;
      restore = 0;
      shared.uBoot.value = 1;
    }

    const pose = worldPose(journey, progress, pointer);
    const boot = shared.uBoot.value;

    // camera: the route pose, a slow sway, and a little pointer parallax beyond the hero
    const sway = animated ? 1 : 0;
    camera.position.set(
      pose.position[0] + sway * Math.sin(clock * 0.23) * 0.03,
      pose.position[1] + sway * Math.sin(clock * 0.31) * 0.014,
      pose.position[2],
    );
    lookTarget.set(pose.target[0], pose.target[1], pose.target[2]);
    camera.up.set(0, 1, 0);
    camera.lookAt(lookTarget);
    const parallax = Math.min(1, Math.max(0, journey - 0.6)) * 0.12;
    if (parallax > 0) {
      right.setFromMatrixColumn(camera.matrix, 0);
      up.setFromMatrixColumn(camera.matrix, 1);
      camera.position.addScaledVector(right, pointer.x * parallax).addScaledVector(up, -pointer.y * parallax * 0.6);
      camera.lookAt(lookTarget);
    }
    // Keep the scene readable on tall phones, and push the picture right on
    // wide screens where the route leaves room for text on the left.
    const aspect = camera.aspect;
    camera.fov = Math.min(84, pose.fov * (aspect < 0.8 ? 1.34 : aspect < 1.25 ? 1.15 : 1));
    const shift = aspect > 1.25 ? pose.shift : 0;
    camera.setViewOffset(width, height, -shift * width, journey < 1 ? -0.02 * height * (1 - journey) : 0, width, height);
    camera.updateProjectionMatrix();

    // atmosphere
    fogColourAt(journey, fogColour);
    (scene.fog as FogExp2).density = pose.fog;
    fog.uFogDensity.value = pose.fog;
    (fog.uFogColor.value as Color).copy(fogColour);
    renderer.setClearColor(fogColour, 1);
    const powered = journey > 1.5 ? 1 : 0.25 + 0.75 * Math.min(1, boot * 1.6);
    playback.intensity = pose.light * powered;

    shared.uTime.value = clock;
    shared.uAlert.value = alert;
    shared.uRestore.value = restore;
    const frame: Frame = { time: clock, delta, pose, boot, alert, recovery: restore, animated };
    for (const part of parts) part.update(frame);

    composer.render(delta);

    if (onStatus && now - statusAt > 160) {
      statusAt = now;
      const status = { zone: zoneLabel(pose), elevation: pose.position[1], progress: journey / LAST_STOP };
      const text = `${status.zone}|${status.elevation.toFixed(1)}|${status.progress.toFixed(2)}`;
      if (text !== statusText) {
        statusText = text;
        onStatus(status);
      }
    }

    if (animated) {
      // Step the resolution down, then bloom off, on devices that cannot keep up.
      measuredFrames += 1;
      if (delta > 0.028) slowFrames += 1;
      if (measuredFrames >= 90) {
        if (slowFrames > 45 && quality < 3) {
          quality += 1;
          if (quality === 3) bloom.enabled = false;
          else resize();
        }
        measuredFrames = 0;
        slowFrames = 0;
      }
      frameId = requestAnimationFrame(draw);
    }
  }

  function requestFrame() {
    if (ready && !frameId && !disposed && visible) frameId = requestAnimationFrame(draw);
  }

  const handleContextLost = (event: Event) => {
    event.preventDefault();
    onContextLost();
  };
  canvas.addEventListener("webglcontextlost", handleContextLost);

  resize();
  // Compile every zone's shaders up front (all zones are still visible here) so
  // arriving somewhere new does not hitch.
  await renderer.compileAsync(scene, camera);
  ready = true;
  draw(performance.now());
  last = 0;

  return {
    setProgress(value) {
      targetProgress = value;
      requestFrame();
    },
    setJourney(u) {
      targetJourney = Number.isFinite(u) ? Math.min(LAST_STOP, Math.max(0, u)) : 0;
      requestFrame();
    },
    setPointer(x, y) {
      pointerTarget.x = x;
      pointerTarget.y = y;
      requestFrame();
    },
    setAnimated(next) {
      animated = next;
      last = 0;
      requestFrame();
    },
    setVisible(next) {
      visible = next;
      last = 0;
      if (visible) requestFrame();
      else if (frameId) {
        cancelAnimationFrame(frameId);
        frameId = 0;
      }
    },
    setAlert(alerting) {
      if (!alerting && alertTarget === 1) restore = 1;
      alertTarget = alerting ? 1 : 0;
      requestFrame();
    },
    resize,
    dispose() {
      disposed = true;
      if (frameId) cancelAnimationFrame(frameId);
      canvas.removeEventListener("webglcontextlost", handleContextLost);
      for (const item of disposables) item.dispose();
      scene.traverse((node) => {
        const mesh = node as Mesh;
        if (!mesh.isMesh) return;
        mesh.geometry?.dispose();
        const materials = Array.isArray(mesh.material) ? mesh.material : [mesh.material];
        for (const material of materials as Material[]) material?.dispose();
      });
      bloom.dispose();
      composer.dispose();
      renderer.dispose();
    },
  };
}
